"""Write synthetic Laplacian stand-in tables for test_roundtrip (not the real, learned tables).

Usage: python3 gen_standin.py   (writes generated/standin_tables.{c,h})
"""

import heapq
import math
from pathlib import Path

N_CH, N_SYM, ESC, M = 7, 130, 129, 32768
STEPS = (1, 3, 40, 300)
# Residual scale per channel in codec units (before dividing by the step).
SCALE = (40.0, 60.0, 25.0, 300.0, 20.0, 150.0, 90.0)
LO = (-5.0, 10.0, 900.0, 0.0, 300.0, 0.0, 0.0)
RNG = (45.0, 90.0, 100.0, 2000.0, 4700.0, 500.0, 500.0)
PF_A = (9830, 9830, 6554, 26214, 19661, 13107, 13107)


def freqs(step, scale):
    b = max(scale / step, 0.4)
    w = [math.exp(-abs(q) / b) for q in range(-64, 65)]
    tail = math.exp(-65 / b)
    tot = sum(w) + 1e-9
    p = [x / tot * (1 - 3e-3) for x in w] + [max(3e-3, tail)]
    s = sum(p)
    p = [x / s for x in p]
    f = [max(1, int(x * M + 0.5)) for x in p]
    top = max(range(N_SYM), key = lambda i: p[i])
    f[top] += M - sum(f)
    assert sum(f) == M and min(f) >= 1
    return f


def huff_lengths(f):
    floor = 1
    while True:
        h = [(max(x, floor), i, (i,)) for i, x in enumerate(f)]
        heapq.heapify(h)
        ln = [0] * len(f)
        while len(h) > 1:
            a, b = heapq.heappop(h), heapq.heappop(h)
            for s in a[2] + b[2]:
                ln[s] += 1
            heapq.heappush(h, (a[0] + b[0], min(a[1], b[1]), a[2] + b[2]))
        if max(ln) <= 15:
            assert abs(sum(2.0**-x for x in ln) - 1.0) < 1e-12
            return ln
        floor *= 2


def rows(vals, per = 16):
    out = []
    for i in range(0, len(vals), per):
        out.append("    " + ", ".join(str(v) for v in vals[i:i + per]) + ",")
    return "\n".join(out)


def main():
    out = Path(__file__).resolve().parent / "generated"
    # Split so that REUSE does not read the generated header text as the license of this script.
    tag = "SPDX-" + "FileCopyrightText: 2026 ETH Zurich and University of Bologna"
    lic = "SPDX-" + "License-Identifier: Apache-2.0"
    spdx = f"/*\n * {tag}\n * {lic}\n *\n * Authors:\n * - Philip Wiese <wiesep@iis.ee.ethz.ch>\n */\n"
    L = len(STEPS)
    h = (spdx + f"""
/* Synthetic stand-in tables for test_roundtrip (generated by gen_standin.py). Sets 1 and 3 are not built. */
#ifndef STANDIN_TABLES_H
#define STANDIN_TABLES_H

#include "sensei_delta.h"

#define STANDIN_N_LEVELS {L}
#define STANDIN_N_SETS 4

extern const struct sensei_delta_tables standin_tables;

#endif
""")
    (out / "standin_tables.h").write_text(h)

    c = spdx + '\n#include "standin_tables.h"\n\n'
    c += "static const uint16_t freq_a[%d][7][130] = {\n" % L
    lens = []
    for step in STEPS:
        c += "{\n"
        lv = []
        for ch in range(N_CH):
            f = freqs(step, SCALE[ch])
            lv.append(huff_lengths(f))
            c += "{\n" + rows(f) + "\n},\n"
        lens.append(lv)
        c += "},\n"
    c += "};\n\nstatic const uint8_t len_a[%d][7][130] = {\n" % L
    for lv in lens:
        c += "{\n"
        for ln in lv:
            c += "{\n" + rows(ln, 26) + "\n},\n"
        c += "},\n"
    c += "};\n\n"
    c += "static const uint16_t level_step[%d] = {%s};\n" % (L, ", ".join(map(str, STEPS)))
    c += "static const double lo[7] = {%s};\n" % ", ".join(repr(float(x)) for x in LO)
    c += "static const double k[7] = {%s};\n" % ", ".join(repr(32768.0 / r) for r in RNG)
    c += "static const int32_t prefilter_a[7] = {%s};\n" % ", ".join(map(str, PF_A))
    c += """
static const struct sensei_delta_set sets[STANDIN_N_SETS] = {
    {freq_a, len_a},
    {0, 0},
    {freq_a, len_a},
    {0, 0},
};

const struct sensei_delta_tables standin_tables = {
    STANDIN_N_SETS, STANDIN_N_LEVELS, level_step, lo, k, prefilter_a, sets,
};
"""
    (out / "standin_tables.c").write_text(c)


main()
